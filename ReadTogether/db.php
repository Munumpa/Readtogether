<?php
// ===================================================================
// DB.PHP - ไฟล์เชื่อมต่อฐานข้อมูล
// ===================================================================
// ไฟล์นี้ทำหน้าที่สร้างการเชื่อมต่อระหว่าง PHP กับฐานข้อมูล MySQL
// และตั้งค่าการเชื่อมต่อให้มีประสิทธิภาพและปลอดภัย

// --- 1. ข้อมูลสำหรับการเชื่อมต่อ (Connection Credentials) ---
$servername = "localhost"; // ที่อยู่ของเซิร์ฟเวอร์ฐานข้อมูล (เครื่องของเราเอง)
$username = "root";        // ชื่อผู้ใช้เริ่มต้นของ XAMPP
$password = "";            // รหัสผ่านเริ่มต้นของ XAMPP (ค่าว่าง)
$dbname = "readtogether_db"; // ชื่อฐานข้อมูลของโปรเจกต์เรา

// --- 2. ตั้งค่าการรายงานข้อผิดพลาดของ MySQLi ---
// บรรทัดนี้จะสั่งให้ MySQLi หยุดการทำงานและแสดงข้อผิดพลาดออกมาทันที
// ถ้ามี Query SQL ใดๆ ที่ทำงานผิดพลาด ช่วยให้ดีบั๊กได้ง่ายขึ้นมาก
mysqli_report(MYSQLI_REPORT_ERROR | MYSQLI_REPORT_STRICT);

try {
    // --- 3. สร้าง Object การเชื่อมต่อ ---
    // เราจะใช้ข้อมูลข้างต้นเพื่อสร้างการเชื่อมต่อ
    $conn = new mysqli($servername, $username, $password, $dbname);

    // --- 4. (สำคัญ!) ตั้งค่า Character Set เป็น utf8mb4 ---
    // เป็นการบอกฐานข้อมูลว่าเราจะส่งและรับข้อมูลเป็นภาษาไทย (และ Emoji)
    // ช่วยป้องกันปัญหา "ภาษาต่างดาว" ได้ 100%
    $conn->set_charset("utf8mb4");

} catch (mysqli_sql_exception $e) {
    // --- 5. จัดการข้อผิดพลาดในการเชื่อมต่อ ---
    // ถ้าการเชื่อมต่อล้มเหลว (เช่น ใส่รหัสผ่านผิด, ชื่อ db ผิด) 
    // โค้ดใน try จะหยุดทำงาน แล้วมาทำงานใน catch นี้แทน
    // เราจะแสดงข้อความที่เป็นมิตรกับผู้ใช้ และเก็บ Error จริงๆ ไว้ดูเอง
    // die() จะหยุดการทำงานของสคริปต์ทั้งหมดทันที
    die("<h1>เกิดข้อผิดพลาดในการเชื่อมต่อฐานข้อมูล</h1><p>ไม่สามารถเชื่อมต่อกับเซิร์ฟเวอร์ฐานข้อมูลได้ กรุณาลองใหม่อีกครั้งในภายหลัง</p>");
    // สำหรับการดีบั๊ก เราสามารถแสดง Error จริงได้:
    // error_log("MySQL Connection Error: " . $e->getMessage());
}

// ถ้าโค้ดวิ่งมาถึงตรงนี้ได้ แสดงว่าการเชื่อมต่อสำเร็จ และตัวแปร $conn พร้อมใช้งาน
?>